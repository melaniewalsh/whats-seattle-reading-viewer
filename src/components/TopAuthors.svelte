						<button role="menuitem" class="share-item img" onclick={shareImage}><span class="share-ic" aria-hidden="true"><ShareIcon size={15} strokeWidth={2} /></span> Share via…</button>
					</div>
				{/if}
			</div>
			{#if shareMsg}<span class="share-msg" role="status">{shareMsg}</span>{/if}
		</div>

		{#if galleryMode}
			<div class="gal-yearnav">
				<button class="gal-arrow" onclick={() => stepYear(1)} disabled={yearIdx >= yearSeq.length - 1} aria-label="Earlier year">‹</button>
				<span class="gal-yearlabel">{year === "all" ? "All time" : year}</span>
				<button class="gal-arrow" onclick={() => stepYear(-1)} disabled={yearIdx <= 0} aria-label="More recent">›</button>
			</div>
			<div class="gallery">
				{#each gallerySections as sec (sec.genre)}
					<section class="gal-sec">
						<div class="gal-head">
							{#if sec.genre !== "All genres"}
								<button class="gal-title gal-title-link" onclick={() => { genre = sec.genre; window.scrollTo({ top: 0 }); }} title="See the full {sec.genre} ranking">{sec.label}</button>
							{:else}
								<h3 class="gal-title">{sec.label}</h3>
							{/if}
						</div>
						<div class="gal-row" onscroll={(e) => e.currentTarget.parentElement.classList.toggle("at-end", e.currentTarget.scrollLeft >= e.currentTarget.scrollWidth - e.currentTarget.clientWidth - 8)}>
							{#each sec.authors as r, i (eachKey(sec.authors, i, rowKey))}
								{@const k = authorKey(r)}
								<article class="gal-card">
									<div class="gal-top">
										<span class="gal-rank">{i + 1}</span>
										<button class="gal-cover gal-portrait" class:has-img={!!portraits[k]} onclick={() => openAuthor(r[0])} title="See borrowing trend">
											{#if portraits[k]}
												<img src={portraits[k]} alt="" width="200" height="200" loading="lazy" />
											{:else}
												<span class="gal-cover-ph" aria-hidden="true">👤</span>
											{/if}
										</button>
									</div>
									<button class="gal-booktitle" onclick={() => openAuthor(r[0])}>{displayName(r[1])}</button>
									<div class="gal-count">{compactNumber(r[2])} checkouts</div>
									{#if k in summaries}
										<p class="gal-sum">{#if summaries[k]}{blurb(summaries[k])} {/if}<span class="src-links"><a class="icon-link" href={wikiUrls[k] || lookupUrls(displayName(r[1])).wikipedia} target="_blank" rel="noopener noreferrer" title="Read more on Wikipedia">Wikipedia&nbsp;<ExtArrow /></a><BorrowMenu q={displayName(r[1])} compact /></span></p>
									{:else}
										<p class="gal-sum gal-sum-ph"></p>
									{/if}
								</article>
							{/each}
						</div>
					</section>
				{/each}
			</div>
		{:else}
			<div class="gal-yearnav">
				<button class="gal-arrow" onclick={() => stepYear(1)} disabled={yearIdx >= yearSeq.length - 1} aria-label="Earlier year">‹</button>
				<span class="gal-yearlabel">{year === "all" ? "All time" : year}</span>
				<button class="gal-arrow" onclick={() => stepYear(-1)} disabled={yearIdx <= 0} aria-label="More recent">›</button>
			</div>
			<p class="ta-caption">
				Most-borrowed authors of <strong>{genre === "All genres" ? "all books" : `${genreLabel(genre)} books`}</strong>
				at the Seattle Public Library, {yearLabel(year)}. <span class="ta-hint">Click a name to see their checkout trend.</span>
			</p>
			<div class="list-layout">
				<div class="list-main">
					{#if rows.length}
					<table class="ta-table">
						<thead>
							<tr>
								<th class="ta-rank">#</th>
								<th class="ta-name">Author</th>
								<th class="ta-count">{year === "all" ? "Checkouts" : `Checkouts in ${year}`}</th>
							</tr>
						</thead>
						<tbody>
							{#each rows as row, i (eachKey(rows, i, rowKey))}
								<tr>
									<td class="ta-rank">{i + 1}</td>
									<td class="ta-name">
										{#if row[0]}
											<!-- The row already shows the summary, More and Borrow, so the
											     name just opens the author's trend page. -->
											<button class="ta-authorlink" title="See this author's checkout trend" onclick={() => openAuthor(row[0])}>{displayName(row[1])}</button>
											{#if authorKey(row) in summaries}
												<p class="row-sum">{#if summaries[authorKey(row)]}{blurb(summaries[authorKey(row)])} {/if}<span class="src-links"><a class="icon-link" href={wikiUrls[authorKey(row)] || lookupUrls(displayName(row[1])).wikipedia} target="_blank" rel="noopener noreferrer" title="Read more on Wikipedia">Wikipedia&nbsp;<ExtArrow /></a><BorrowMenu q={displayName(row[1])} compact /></span></p>
											{/if}
										{:else}
											{displayName(row[1])}
										{/if}
									</td>
									<td class="ta-count">
										<div class="ta-num" title={row[2].toLocaleString()}>{compactNumber(row[2])}</div>
									</td>
								</tr>
							{/each}
						</tbody>
					</table>
					{:else}
						<p class="ta-status">No authors for this genre and year.</p>
					{/if}
				</div>
				<aside class="list-aside">
					{#if genreTags.length}
						<div class="aside-card">
							<div class="aside-h">Subject tags · {genre}</div>
							<p class="ta-tags">{#each genreTags as t}<code class="ta-tag">{t}</code>{/each}</p>
						</div>
					{/if}
					<div class="aside-card">
						<div class="aside-h">About these counts</div>
						<p class="aside-p">These counts represent aggregate checkouts of each author's works as print books, ebooks, and audiobooks. Different spellings of an author's name are automatically grouped together, and these groupings are imperfect. The counts do not include holds or renewals.</p>
					</div>
				</aside>
			</div>
		{/if}
	{/if}

</div>

