<script>
	import { onMount } from "svelte";
	import { getTopAuthors } from "$components/db.js";

	// openAuthor(slug) is provided by Index.svelte: jumps to the By-author view.
	let { openAuthor } = $props();

	let data = $state(null);
	let genre = $state("All genres");
	let year = $state("all"); // "all" or a 4-digit year string
	let loading = $state(true);
	let loadError = $state("");
	let shareMsg = $state("");

	onMount(async () => {
		// Read shareable filters from the URL first.
		try {
			const p = new URLSearchParams(window.location.search);
			if (p.get("genre")) genre = p.get("genre");
			if (p.get("year")) year = p.get("year");
		} catch {}
		const d = await getTopAuthors();
		loading = false;
		if (!d || !d.genres) {
			loadError =
				"Couldn't load the top-authors data. (It's generated by the data build — on the live site it loads; in local preview it may not be present yet.)";
			return;
		}
		data = d;
		if (!data.genres.includes(genre)) genre = data.genres[0];
		if (year !== "all" && !data.years.includes(Number(year))) year = "all";
	});

	const rows = $derived.by(() => {
		if (!data) return [];
		const g = data.data[genre];
		if (!g) return [];
		return (g[year] || []).slice(0, 10);
	});

	// Keep the URL in sync so any view is shareable / reloadable.
	$effect(() => {
		if (!data) return;
		try {
			const url = new URL(window.location);
			url.searchParams.set("tab", "top");
			url.searchParams.set("genre", genre);
			url.searchParams.set("year", year);
			url.searchParams.delete("author");
			window.history.replaceState({}, "", url);
		} catch {}
	});

	// Clean a canonical name ("thurber, james, 1894" / "cathy l greenberg") into
	// a readable "First Last" — same rules as the By-author view.
	function titleCaseWord(w) {
		if (w.length <= 2 && w === w.toLowerCase() && /[a-z]/.test(w)) {
			// initials like "j" / "jr" -> uppercase
			return w.toUpperCase();
		}
		return w.charAt(0).toUpperCase() + w.slice(1);
	}
	function displayName(name) {
		if (!name) return name;
		let n = name.trim();
		n = n.replace(/,\s*\d{4}(?:\s*-\s*\d{0,4})?\.?\s*$/, "");
		const comma = n.match(/^([^,]+),\s*(.+)$/);
		if (comma) n = `${comma[2].trim()} ${comma[1].trim()}`;
		return n.replace(/\S+/g, titleCaseWord);
	}

	async function copyLink() {
		try {
			await navigator.clipboard.writeText(window.location.href);
			shareMsg = "Link copied!";
			setTimeout(() => (shareMsg = ""), 2000);
		} catch {
			shareMsg = "";
		}
	}

	const yearLabel = (y) => (y === "all" ? "all time" : y);
</script>

<div class="top-authors">
	{#if loading}
		<p class="ta-status">Loading…</p>
	{:else if loadError}
		<p class="ta-status ta-error">{loadError}</p>
	{:else if data}
		<div class="ta-controls">
			<label class="ta-field">
				<span>Genre</span>
				<select bind:value={genre}>
					{#each data.genres as g}
						<option value={g}>{g}</option>
					{/each}
				</select>
			</label>
			<label class="ta-field">
				<span>Year</span>
				<select bind:value={year}>
					<option value="all">All time</option>
					{#each [...data.years].reverse() as y}
						<option value={String(y)}>{y}</option>
					{/each}
				</select>
			</label>
			<button class="ta-share" onclick={copyLink} title="Copy a link to this exact view">
				Share
			</button>
			{#if shareMsg}<span class="ta-sharemsg" role="status">{shareMsg}</span>{/if}
		</div>

		<p class="ta-caption">
			Most-borrowed authors of <strong>{genre === "All genres" ? "all books" : `${genre} books`}</strong>
			at the Seattle Public Library, {yearLabel(year)}.
		</p>

		{#if rows.length}
			<table class="ta-table">
				<thead>
					<tr>
						<th class="ta-rank">#</th>
						<th class="ta-name">Author</th>
						<th class="ta-count">Checkouts</th>
					</tr>
				</thead>
				<tbody>
					{#each rows as row, i (row[0] + row[1])}
						<tr>
							<td class="ta-rank">{i + 1}</td>
							<td class="ta-name">
								{#if row[0]}
									<button class="ta-authorlink" onclick={() => openAuthor(row[0])}
										>{displayName(row[1])}</button>
								{:else}
									{displayName(row[1])}
								{/if}
							</td>
							<td class="ta-count">{row[2].toLocaleString()}</td>
						</tr>
					{/each}
				</tbody>
			</table>
		{:else}
			<p class="ta-status">No authors for this genre and year.</p>
		{/if}
	{/if}
</div>

