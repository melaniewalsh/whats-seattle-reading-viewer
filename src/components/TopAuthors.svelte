<script>
	import ExtArrow from "$components/ExtArrow.svelte";
	import { onMount, onDestroy, untrack } from "svelte";
	import ImageIcon from "@lucide/svelte/icons/image";
	import LinkIcon from "@lucide/svelte/icons/link";
	import ShareIcon from "@lucide/svelte/icons/share-2";
	import { getTopAuthors, getGenreTerms } from "$components/db.js";
	import { displayName } from "$utils/displayName.js";
	import { lookupUrls } from "$utils/lookup.js";
	import { compactNumber, blurb } from "$utils/format.js";
	import { renderTableBlob, shareTableImage, copyTableImage, copyPageLink } from "$utils/tableExport.js";
	import { eachKey } from "$utils/eachKey.js";
	import { curateGenres, extraGenres, genreLabel } from "$utils/rankGenres.js";
	import { wikiSummary } from "$utils/wiki.js";
	import BorrowMenu from "$components/BorrowMenu.svelte";

	// openAuthor(slug) is provided by Index.svelte: jumps to the By-author view.
	// rankKind / setRankKind drive the Type dropdown that swaps Works ⇄ Authors.
	let { openAuthor, rankKind = "authors", setRankKind = () => {} } = $props();

	let data = $state.raw(null);
	let genre = $state("All genres");
	let year = $state("all"); // "all" or a 4-digit year string
	let loading = $state(true);
	let loadError = $state("");
	let shareMsg = $state("");
	// One timer for the toast, so a second message isn't cleared early by the first one's timer.
	let flashTimer;
	function flash(msg, ms = 2600) {
		clearTimeout(flashTimer);
		shareMsg = msg;
		flashTimer = setTimeout(() => (shareMsg = ""), ms);
	}
	onDestroy(() => clearTimeout(flashTimer));
	let shareOpen = $state(false);
	let termsMap = $state.raw({});
	onMount(async () => {
		// Read shareable filters from the URL first.
		try {
			const p = new URLSearchParams(window.location.search);
			if (p.get("genre")) genre = p.get("genre");
			if (p.get("year")) year = p.get("year");
		} catch {}
		getGenreTerms().then((m) => (termsMap = m));
		const d = await getTopAuthors();
		loading = false;
		if (!d || !d.genres) {
			loadError =
				"Couldn't load the top-authors data. (It's generated by the data build — on the live site it loads; in local preview it may not be present yet.)";
			return;
		}
		data = d;
		if (!data.genres.includes(genre)) genre = "All genres";
		if (year !== "all" && !data.years.includes(Number(year))) year = "all";
	});
	// Curated genres (gallery + top of the dropdown) and the rest (filterable
	// under a divider).
	const genreList = $derived(data ? curateGenres(data.genres) : []);
	const extra = $derived(data ? extraGenres(data.genres) : []);

	const rows = $derived.by(() => {
		if (!data) return [];
		const g = data.data[genre];
		if (!g) return [];
		return (g[year] || []).slice(0, 10);
	});

	// The catalog subject tags that define the selected genre (empty for "All genres").
	const genreTags = $derived(genre !== "All genres" ? (termsMap[genre] || []) : []);

	// GALLERY (default, unfiltered view): a NYT Best Sellers–style browse where each
	// genre gets a row of author portraits with a short bio beneath. Choosing a
	// specific genre drops to the vertical ranking table. rows are [slug, name, count].
	const galleryMode = $derived(!!data && genre === "All genres");
	const gallerySections = $derived.by(() => {
		if (!data) return [];
		const secs = [];
		for (const g of genreList) {
			const authors = (data.data[g]?.[year] || []).slice(0, 5);
			if (authors.length)
				secs.push({
					genre: g,
					label: g === "All genres" ? "Most borrowed overall" : `Top in ${genreLabel(g)}`,
					authors,
				});
		}
		return secs;
	});
	const galleryAuthors = $derived(gallerySections.flatMap((s) => s.authors));

	// Year stepper for gallery mode: ["all", 2025, 2024, …]. ‹ toward all-time, › older.
	const yearSeq = $derived(data ? ["all", ...[...data.years].reverse().map(String)] : ["all"]);
	const yearIdx = $derived(yearSeq.indexOf(String(year)));
	function stepYear(delta) {
		const i = yearIdx + delta;
		if (i >= 0 && i < yearSeq.length) year = yearSeq[i];
	}

	// Wikipedia portrait + bio for each gallery card. thumbnail | null (none) |
	// undefined (not fetched). One request per author, shared for both.
	let portraits = $state.raw({});
	let summaries = $state.raw({});
	let wikiUrls = $state.raw({});
	const cardInflight = new Set();
	const authorKey = (r) => r[1];
	// {#each} key for a row: the author's slug (some rows have none: their name).
	const rowKey = (r) => r[0] || `name:${r[1]}`;
	function loadCard(r) {
		const k = authorKey(r);
		if (k in portraits || cardInflight.has(k)) return;
		cardInflight.add(k);
		wikiSummary(displayName(r[1])).then((w) => {
			portraits = { ...portraits, [k]: w?.thumbnail || null };
			summaries = { ...summaries, [k]: w?.extract || null };
			wikiUrls = { ...wikiUrls, [k]: w?.url || null };
		});
	}
	// Load portraits/blurbs for whatever's on screen — gallery cards or ranking
	// rows. Re-runs only when that list changes, not on every portrait that
	// arrives (loadCard reads and writes them).
	$effect(() => {
		const list = galleryMode ? galleryAuthors : rows;
		untrack(() => {
			for (const r of list) loadCard(r);
		});
	});

	// Keep the URL in sync so any view is shareable / reloadable.
	$effect(() => {
		if (!data) return;
		try {
			const url = new URL(window.location);
			url.searchParams.set("tab", "top");
			url.searchParams.set("genre", genre);
			url.searchParams.set("year", year);
			url.searchParams.delete("author");
			window.history.replaceState({}, "", url);
		} catch {}
	});

	const yearLabel = (y) => (y === "all" ? "all time" : y);

	function shareTarget() {
		const link = window.location.href;
		const who = genre === "All genres" ? "authors" : `${genreLabel(genre)} authors`;
		const when = year === "all" ? "" : `, ${year}`;
		const text = `What’s Seattle Reading? — Top ${who}${when}`;
		return { link, text };
	}

	// Draw the current top-10 table to a PNG so people can share the ranking as
	// an image (the same idea as the chart views' exported image).
	function renderTable() {
		return renderTableBlob({
			title: genre === "All genres" ? "Most-borrowed authors" : `Top ${genreLabel(genre)} authors`,
			subtitle: `Seattle Public Library · ${yearLabel(year)}`,
			column: "AUTHOR",
			rows,
			count: (r) => r[2],
			name: (r) => [displayName(r[1])],
			rowH: 38,
			lineDy: 24,
		});
	}

	function imgName() {
		const g = genre === "All genres" ? "top-authors" : `top-${genre.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`;
		return `seattle-reading-${g}-${year}.png`.replace(/-+/g, "-");
	}

	function shareImage() {
		shareOpen = false;
		return shareTableImage(renderTable, imgName(), shareTarget(), flash);
	}

	function copyImage() {
		shareOpen = false;
		return copyTableImage(renderTable, imgName(), flash);
	}

	async function copyShareLink() {
		await copyPageLink(flash);
		shareOpen = false;
	}
</script>

<div class="top-authors" class:wide={galleryMode}>
	{#if loading}
		<p class="ta-status">Loading…</p>
