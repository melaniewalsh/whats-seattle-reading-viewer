					<span aria-hidden="true">↗</span> Share
				</button>
				{#if shareOpen}
					<button class="share-backdrop" aria-label="Close share menu" onclick={() => (shareOpen = false)}></button>
					<div class="share-menu" role="menu">
						<button role="menuitem" class="share-item fb" onclick={() => shareTo("facebook")}><span class="share-ic" aria-hidden="true">f</span> Facebook</button>
						<button role="menuitem" class="share-item tw" onclick={() => shareTo("twitter")}><span class="share-ic" aria-hidden="true">𝕏</span> Twitter</button>
						<button role="menuitem" class="share-item bs" onclick={() => shareTo("bluesky")}><span class="share-ic" aria-hidden="true">🦋</span> Bluesky</button>
						<button role="menuitem" class="share-item li" onclick={() => shareTo("linkedin")}><span class="share-ic" aria-hidden="true">in</span> LinkedIn</button>
						<div class="share-sep"></div>
						<button role="menuitem" class="share-item img" onclick={shareImage}><span class="share-ic" aria-hidden="true">▦</span> Share image</button>
						<button role="menuitem" class="share-item copyimg" onclick={copyImage}><span class="share-ic" aria-hidden="true">⧉</span> Copy image</button>
						<button role="menuitem" class="share-item dl" onclick={downloadImage}><span class="share-ic" aria-hidden="true">⤓</span> Download image</button>
						<button role="menuitem" class="share-item copy" onclick={copyShareLink}><span class="share-ic" aria-hidden="true">🔗</span> Copy link</button>
					</div>
				{/if}
			</div>
			{#if shareMsg}<span class="share-msg" role="status">{shareMsg}</span>{/if}
		</div>

		<p class="ta-caption">
			Most-borrowed <strong>{genre === "All genres" ? "works" : `${genre} works`}</strong>
			at the Seattle Public Library, {yearLabel(year)}.
		</p>

		<details class="ta-note">
			<summary>Counts print books, ebooks &amp; audiobooks</summary>
			<p>Editions of a book (print, ebook, audiobook, reprints) are grouped into one work. These are raw <strong>checkouts</strong> — they don't include holds or renewals, and the clustering is automatic and approximate. Read the rankings as a good sense of what's popular, not an exact or official count.</p>
		</details>

		{#if rows.length}
			<table class="ta-table">
				<thead>
					<tr>
						<th class="ta-rank">#</th>
						<th class="ta-name">Work</th>
						<th class="ta-count">Checkouts</th>
					</tr>
				</thead>
				<tbody>
					{#each rows as row, i (row[0] + row[2] + i)}
						<tr>
							<td class="ta-rank">{i + 1}</td>
							<td class="ta-name">
								<button class="tw-title tw-titlelink" onclick={() => openTitle(row[0])} title="See this title's checkout trend">{row[0]}</button>
								{#if row[2]}
									<button class="tw-by ta-authorlink" onclick={() => openAuthor(row[2])}>by {displayName(row[1])}</button>
								{:else}
									<span class="tw-by">by {displayName(row[1])}</span>
								{/if}
							</td>
							<td class="ta-count">{row[3].toLocaleString()}</td>
						</tr>
					{/each}
				</tbody>
			</table>
		{:else}
			<p class="ta-status">No works for this genre and year.</p>
		{/if}
	{/if}
</div>

