<script>
	import ExtArrow from "$components/ExtArrow.svelte";
	import { onMount } from "svelte";
	import ImageIcon from "@lucide/svelte/icons/image";
	import LinkIcon from "@lucide/svelte/icons/link";
	import ShareIcon from "@lucide/svelte/icons/share-2";
	import { base } from "$app/paths";
	import { getTopWorks, getGenreTerms } from "$components/db.js";
	import homeTop from "$data/home-top.json";
	import { displayName } from "$utils/displayName.js";
	import { coverUrl, coverOverride } from "$utils/covers.js";
	import { lookupUrls } from "$utils/lookup.js";
	import { wikiWork } from "$utils/wiki.js";
	import { compactNumber } from "$utils/format.js";
	import { titleCase } from "$utils/titleCase.js";
	import { cleanWorkTitle, searchTitle } from "$utils/cleanTitle.js";
	import { curateGenres, extraGenres, genreLabel } from "$utils/rankGenres.js";
	import BorrowMenu from "$components/BorrowMenu.svelte";

	// openAuthor(slug) / openTitle(title, slug) are provided by Index.svelte: jump to the
	// By-author / By-title views. rankKind / setRankKind drive the Type dropdown that
	// swaps between the Works and Authors rankings.
	// embedded: render ONLY the "Most borrowed overall (last month)" gallery strip
	// (no masthead / controls / table) for the home page. onSeeAll links to the full
	// Most Borrowed view.
	let { openAuthor, openTitle, rankKind = "works", setRankKind = () => {}, embedded = false, onSeeAll = () => {} } = $props();

	// The home strip uses the five books baked in at build time
	// (data-prep/build_home_top.py), set up front so they're in the pre-built
	// HTML: no 2.6 MB rankings download, no wait.
	const baked = embedded && homeTop?.rows?.length
		? { period: homeTop.latestMonth ? "month" : "all", rows: homeTop.rows, latestMonth: homeTop.latestMonth }
		: null;
	let data = $state.raw(baked ? { latestMonth: baked.latestMonth, years: [], genres: ["All genres"], data: { "All genres": { [baked.period]: baked.rows } } } : null);
	let genre = $state("All genres");
	let year = $state(baked ? baked.period : "all");
	let loading = $state(!baked);
	let loadError = $state("");
	let shareMsg = $state("");
	let shareOpen = $state(false);
	let termsMap = $state({});
	onMount(async () => {
		if (baked) return; // the home strip already has its books
		let yearFromUrl = false;
		try {
			const p = new URLSearchParams(window.location.search);
			if (p.get("genre")) genre = p.get("genre");
			if (p.get("year")) { year = p.get("year"); yearFromUrl = true; }
		} catch {}
		getGenreTerms().then((m) => (termsMap = m));
		const d = await getTopWorks();
		loading = false;
		if (!d || !d.genres) {
			loadError =
				"Couldn't load the top-works data. (It's generated by the data build — on the live site it loads; in local preview it may not be present yet.)";
			return;
		}
		data = d;
		if (!data.genres.includes(genre)) genre = "All genres";
		// Default to last month's ranking (the freshest, most timely view) when the
		// data has it, unless the URL asked for a specific period.
		if (!yearFromUrl && data.latestMonth) year = "month";
		if (year === "month") { if (!data.latestMonth) year = "all"; }
		else if (year !== "all" && !data.years.includes(Number(year))) year = "all";
	});
	// Curated genres (gallery + top of the dropdown) and the rest (filterable
	// under a divider).
	const genreList = $derived(data ? curateGenres(data.genres) : []);
	const extra = $derived(data ? extraGenres(data.genres) : []);

	// rows are [title, author, slug, checkouts]
	const rows = $derived.by(() => {
		if (!data) return [];
		const g = data.data[genre];
		if (!g) return [];
		return (g[year] || []).slice(0, 10);
	});

	// The catalog subject tags that define the selected genre (empty for "All genres").
	const genreTags = $derived(genre !== "All genres" ? (termsMap[genre] || []) : []);

	// Largest count in view — scales the in-row data bars so #1 fills the column.
	const maxCount = $derived(rows.length ? Math.max(...rows.map((r) => r[3])) : 1);

	// Book-cover thumbnails. Open Library first; when it has nothing, fall back to
	// the Wikipedia/Wikidata article thumbnail (usually the book's cover). covers[key]
	// = url | null (no cover) | undefined (not fetched yet). Cached once per work.
	const coverKey = (r) => `${r[0]}|${r[1]}`;
	// The baked home rows carry their cover URLs, so those are in the HTML too.
	let covers = $state(baked ? Object.fromEntries(baked.rows.filter((r) => r[4]).map((r) => [coverKey(r), r[4]])) : {});
	const coverInflight = new Set();
	const wikiTried = new Set();
	// Backup cover: the Wikipedia/Wikidata article thumbnail (usually the book's
	// cover). Tried once per work when Open Library has nothing or its image fails
	// to load; on a second failure we settle for the placeholder.
	function fillFromWiki(r) {
		const k = coverKey(r);
		if (wikiTried.has(k)) {
			covers = { ...covers, [k]: null };
			return;
		}
		wikiTried.add(k);
		wikiWork(searchTitle(r[0]), displayName(r[1])).then((w) => {
			covers = { ...covers, [k]: w?.thumbnail || null };
		});
	}
	$effect(() => {
		for (const r of rows) {
			const k = coverKey(r);
			if (k in covers || coverInflight.has(k)) continue;
			coverInflight.add(k);
			// A manual override (covers.js) wins over everything. Otherwise r[4] = the
			// cover baked at build time; anything else resolves at runtime.
			const ov = coverOverride(r[0]);
			const baked = r[4];
			if (ov) {
				covers = { ...covers, [k]: ov };
			} else if (typeof baked === "string" && baked) {
				covers = { ...covers, [k]: baked };
			} else {
				coverUrl(r[0], displayName(r[1])).then((u) => {
					if (u) covers = { ...covers, [k]: u };
					else fillFromWiki(r);
				});
			}
		}
	});

	// GALLERY (default, unfiltered view): a NYT Best Sellers–style browse where each
	// genre gets a row of large book covers with a short blurb beneath. The moment a
	// filter (a specific genre, or any year) is chosen we drop to the vertical ranking
	// table instead — the gallery is only for the "everything, all-time" landing.
	// "Most borrowed overall" can be opened as its own top-10 list (like the genre
	// pages) instead of only appearing as a 5-card row in the gallery.
	let overallList = $state(false);
	const galleryMode = $derived(!!data && genre === "All genres" && !overallList);
	const gallerySections = $derived.by(() => {
		if (!data) return [];
		const secs = [];
		for (const g of genreList) {
			const books = (data.data[g]?.[year] || []).slice(0, 5);
			if (books.length)
				secs.push({
					genre: g,
					label: g === "All genres" ? "Most borrowed overall" : `Top in ${genreLabel(g)}`,
					books,
				});
		}
		return secs;
	});
	const galleryBooks = $derived(gallerySections.flatMap((s) => s.books));
	// The overall (all-genre) top 5 for the current period — used by the embedded
	// home strip.
	const overallBooks = $derived(data ? (data.data["All genres"]?.[year] || []).slice(0, 5) : []);

	// The single freshest month of data (from the build), e.g. "2026-07", shown as
	// its own "this month" ranking. Only present once the data has been rebuilt with
	// it; older data just omits the option.
	const latestMonth = $derived(data?.latestMonth || null);
	const monthLabel = $derived(latestMonth ? fmtMonth(latestMonth) : "");
	let lagOpen = $state(false); // the "?" note on when new data is published
	// Short form ("Aug 2026") for the compact labels next to "Last month".
	const monthShort = $derived(monthLabel ? monthLabel.replace(/^(\w{3})\w*/, "$1") : "");
	function fmtMonth(ym) {
		const [y, m] = (ym || "").split("-");
		const names = ["January","February","March","April","May","June","July","August","September","October","November","December"];
		return m ? `${names[Number(m) - 1]} ${y}` : ym;
	}

	// Year stepper for gallery mode (NYT "previous week" arrows). The freshest month
	// leads, then all-time, then years newest→oldest. ‹ steps toward older, › newer.
	const yearSeq = $derived(
		data ? [...(latestMonth ? ["month"] : []), "all", ...[...data.years].reverse().map(String)] : ["all"]
	);
	const yearIdx = $derived(yearSeq.indexOf(String(year)));
	function stepYear(delta) {
		const i = yearIdx + delta;
		if (i >= 0 && i < yearSeq.length) year = yearSeq[i];
	}

	// Wikipedia blurbs for the gallery cards: extract | null (no article) | undefined
	// (not fetched yet). One request per work, shared with the cover fallback so a work
	// that Open Library can't cover still gets its Wikipedia thumbnail here.
	let summaries = $state({});
	let wikiUrls = $state({});
	const summaryInflight = new Set();
	function loadCard(r) {
		const k = coverKey(r);
		if (!(k in covers) && !coverInflight.has(k)) {
			coverInflight.add(k);
			const ov = coverOverride(r[0]);
			const baked = r[4];
			if (ov) {
				covers = { ...covers, [k]: ov };
			} else if (typeof baked === "string" && baked) {
				covers = { ...covers, [k]: baked };
			} else {
				coverUrl(r[0], displayName(r[1])).then((u) => {
					if (u) covers = { ...covers, [k]: u };
					else fillFromWiki(r);
				});
			}
		}
		if (!(k in summaries) && !summaryInflight.has(k)) {
			summaryInflight.add(k);
			wikiWork(searchTitle(r[0]), displayName(r[1])).then((w) => {
				summaries = { ...summaries, [k]: w?.extract || null };
				wikiUrls = { ...wikiUrls, [k]: w?.url || null };
				if (!covers[k] && w?.thumbnail) covers = { ...covers, [k]: w.thumbnail };
			});
		}
	}
	// Load blurbs for whatever's on screen — the gallery cards or the ranking rows.
	$effect(() => {
		const list = embedded ? overallBooks : galleryMode ? galleryBooks : rows;
		for (const r of list) loadCard(r);
	});
	// Trim a Wikipedia extract to a short blurb, breaking on a word boundary.
	function blurb(s, max = 200) {
		if (!s) return "";
		if (s.length <= max) return s;
		return s.slice(0, max).replace(/\s+\S*$/, "") + "…";
	}

	// Keep the Most Borrowed page's filters in the URL. Not for the home strip:
	// it isn't that page, and (with its books baked in) it would rewrite the
	// URL on load before the site reads it, sending /?author=… links to the
	// rankings.
	$effect(() => {
		if (!data || embedded) return;
		try {
			const url = new URL(window.location);
			url.searchParams.set("tab", "works");
			url.searchParams.set("genre", genre);
			url.searchParams.set("year", year);
			url.searchParams.delete("author");
			window.history.replaceState({}, "", url);
		} catch {}
	});


	const yearLabel = (y) => (y === "all" ? "all time" : y === "month" ? monthLabel : y);

	function shareTarget() {
		const link = window.location.href;
		const who = genre === "All genres" ? "works" : `${genreLabel(genre)} works`;
		const when = year === "all" ? "" : `, ${year}`;
		const text = `What’s Seattle Reading? — Top ${who}${when}`;
		return { link, text };
	}

	const IMG_SANS = '-apple-system, BlinkMacSystemFont, "Segoe UI", Helvetica, Arial, sans-serif';
	function ellipsize(ctx, s, maxW) {
		if (ctx.measureText(s).width <= maxW) return s;
		while (s.length > 1 && ctx.measureText(s + "…").width > maxW) s = s.slice(0, -1);
		return s + "…";
	}
	async function renderTableBlob() {
		const list = rows;
		if (!list.length) return null;
		const scale = 2, W = 640, padX = 32;
		const titleH = 92, headH = 30, rowH = 50, footH = 44;
		const H = titleH + headH + rowH * list.length + footH;
		const canvas = document.createElement("canvas");
		canvas.width = W * scale;
		canvas.height = H * scale;
		const ctx = canvas.getContext("2d");
		ctx.scale(scale, scale);
		ctx.fillStyle = "#ffffff";
		ctx.fillRect(0, 0, W, H);
		ctx.textBaseline = "alphabetic";

		const title = genre === "All genres" ? "Most-borrowed works" : `Top ${genreLabel(genre)} works`;
		ctx.fillStyle = "#1a1a1a";
		ctx.font = '600 24px Georgia, "Times New Roman", serif';
		ctx.fillText(ellipsize(ctx, title, W - padX * 2), padX, 46);
		ctx.fillStyle = "#666666";
		ctx.font = `13px ${IMG_SANS}`;
		ctx.fillText(`Seattle Public Library · ${yearLabel(year)}`, padX, 68);

		// The count column is [abbreviated number][data bar], matching the on-screen table.
		const rightX = W - padX;
		const barTrackW = 150;
		const barX0 = rightX - barTrackW; // bars start here, grow rightward
		const numX = barX0 - 14; // right edge of the right-aligned number
		const numColLeft = numX - 54; // left edge of the number label
		let y = titleH;
		ctx.fillStyle = "#999999";
		ctx.font = `700 11px ${IMG_SANS}`;
		ctx.textAlign = "left";
		ctx.fillText("#", padX, y);
		ctx.fillText("WORK", padX + 40, y);
		ctx.fillText("CHECKOUTS", numColLeft, y);
		ctx.strokeStyle = "#dddddd";
		ctx.lineWidth = 1;
		ctx.beginPath();
		ctx.moveTo(padX, y + 9);
		ctx.lineTo(rightX, y + 9);
		ctx.stroke();

		y += headH;
		const max = maxCount || 1;
		list.forEach((r, i) => {
			const baseY = y + rowH * i;
			const lineY = baseY + 22; // the title line — count/bar align to it
			ctx.fillStyle = "#999999";
			ctx.font = `13px ${IMG_SANS}`;
			ctx.textAlign = "left";
			ctx.fillText(String(i + 1), padX, lineY);
			// abbreviated count, right-aligned
			ctx.fillStyle = "#1a1a1a";
			ctx.font = `600 14px ${IMG_SANS}`;
			ctx.textAlign = "right";
			ctx.fillText(compactNumber(r[3]), numX, lineY);
			// data bar
			ctx.fillStyle = "#3f88cc";
			ctx.beginPath();
			ctx.roundRect(barX0, lineY - 13, Math.max((r[3] / max) * barTrackW, 4), 16, 3);
			ctx.fill();
			// title + author
			ctx.textAlign = "left";
			const nameMaxW = numColLeft - 12 - (padX + 40);
			ctx.fillStyle = "#1a1a1a";
			ctx.font = `600 15px ${IMG_SANS}`;
			ctx.fillText(ellipsize(ctx, titleCase(cleanWorkTitle(r[0])), nameMaxW), padX + 40, lineY);
			ctx.fillStyle = "#777777";
			ctx.font = `13px ${IMG_SANS}`;
			ctx.fillText(ellipsize(ctx, "by " + displayName(r[1]), nameMaxW), padX + 40, baseY + 39);
			ctx.strokeStyle = "#eeeeee";
			ctx.beginPath();
			ctx.moveTo(padX, baseY + rowH);
			ctx.lineTo(rightX, baseY + rowH);
			ctx.stroke();
		});

		ctx.fillStyle = "#999999";
		ctx.font = `11px ${IMG_SANS}`;
		ctx.fillText("What’s Seattle Reading?  ·  Seattle Public Library checkouts", padX, H - 18);
		return await new Promise((resolve) => canvas.toBlob(resolve, "image/png"));
	}

	function imgName() {
		const g = genre === "All genres" ? "top-works" : `top-${genre.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-works`;
		return `seattle-reading-${g}-${year}.png`.replace(/-+/g, "-");
	}
	function saveBlob(blob, name) {
		const a = document.createElement("a");
		a.href = URL.createObjectURL(blob);
		a.download = name;
		a.click();
		setTimeout(() => URL.revokeObjectURL(a.href), 1000);
	}

	function shareTo(platform) {
		const { link, text } = shareTarget();
		let copied = false;
		try {
			if (navigator.clipboard && window.ClipboardItem) {
				navigator.clipboard.write([new ClipboardItem({ "image/png": renderTableBlob() })]).catch(() => {});
				copied = true;
			}
		} catch {}
		const u = encodeURIComponent(link);
		const t = encodeURIComponent(text);
		const urls = {
			facebook: `https://www.facebook.com/sharer/sharer.php?u=${u}`,
			twitter: `https://twitter.com/intent/tweet?url=${u}&text=${t}`,
			bluesky: `https://bsky.app/intent/compose?text=${encodeURIComponent(text + " " + link)}`,
			linkedin: `https://www.linkedin.com/sharing/share-offsite/?url=${u}`,
		};
		if (urls[platform]) window.open(urls[platform], "_blank", "noopener,noreferrer,width=600,height=540");
		shareOpen = false;
		if (copied) {
			shareMsg = "Table image copied — paste it (⌘/Ctrl+V) into your post";
			setTimeout(() => (shareMsg = ""), 4500);
		}
	}

	async function shareImage() {
		shareOpen = false;
		const blob = await renderTableBlob();
		if (!blob) return;
		const name = imgName();
		const file = new File([blob], name, { type: "image/png" });
		const { link, text } = shareTarget();
		if (navigator.canShare && navigator.canShare({ files: [file] })) {
			try {
				await navigator.share({ files: [file], title: text, text: `${text}\n${link}` });
			} catch {}
			return;
		}
		saveBlob(blob, name);
		shareMsg = "Image saved — attach it to your post";
		setTimeout(() => (shareMsg = ""), 3200);
	}

	async function copyImage() {
		shareOpen = false;
		try {
			if (!(navigator.clipboard && window.ClipboardItem)) throw new Error("no clipboard");
			await navigator.clipboard.write([new ClipboardItem({ "image/png": renderTableBlob() })]);
			shareMsg = "Table image copied to clipboard";
		} catch {
			const blob = await renderTableBlob();
			if (blob) saveBlob(blob, imgName());
			shareMsg = "Image saved (clipboard unavailable)";
		}
		setTimeout(() => (shareMsg = ""), 2600);
	}

	async function downloadImage() {
		shareOpen = false;
		const blob = await renderTableBlob();
		if (blob) saveBlob(blob, imgName());
	}

	async function copyShareLink() {
		try {
			await navigator.clipboard.writeText(window.location.href);
		} catch {}
		shareMsg = "Link copied!";
		setTimeout(() => (shareMsg = ""), 2000);
		shareOpen = false;
	}
</script>

<div class="top-authors" class:wide={galleryMode}>
	{#if loading}
		<p class="ta-status">Loading…</p>
	{:else if loadError}
		<p class="ta-status ta-error">{loadError}</p>
	{:else if data}
		{#snippet galCard(r, i)}
			{@const k = coverKey(r)}
			<article class="gal-card">
				<div class="gal-top">
					<span class="gal-rank">{i + 1}</span>
					<button class="gal-cover" class:has-img={!!covers[k]} onclick={() => openTitle(r[0], r[2])} title="See borrowing trend">
						{#if covers[k]}
							<img src={covers[k]} alt="" loading={embedded ? "eager" : "lazy"} onerror={() => fillFromWiki(r)} />
						{:else}
							<span class="gal-cover-ph" aria-hidden="true">📖</span>
						{/if}
					</button>
				</div>
				<button class="gal-booktitle" onclick={() => openTitle(r[0], r[2])}>{titleCase(cleanWorkTitle(r[0]))}</button>
				<div class="gal-by">by {displayName(r[1])}</div>
				<div class="gal-count">{compactNumber(r[3])} checkouts</div>
				{#if !embedded}
					{#if k in summaries}
						<p class="gal-sum">{#if summaries[k]}{blurb(summaries[k])} {/if}<span class="src-links"><a class="icon-link" href={wikiUrls[k] || lookupUrls(`${r[0]} ${displayName(r[1])}`).wikipedia} target="_blank" rel="noopener noreferrer" title="Read more on Wikipedia">Wikipedia&nbsp;<ExtArrow /></a><BorrowMenu q={`${r[0]} ${displayName(r[1])}`} compact /></span></p>
					{:else}
						<p class="gal-sum gal-sum-ph"></p>
					{/if}
				{/if}
			</article>
		{/snippet}
		{#snippet galRow(books)}
			<div class="gal-row" onscroll={(e) => e.currentTarget.parentElement.classList.toggle("at-end", e.currentTarget.scrollLeft >= e.currentTarget.scrollWidth - e.currentTarget.clientWidth - 8)}>
				{#each books as r, i (r[0] + r[2] + i)}
					{@render galCard(r, i)}
				{/each}
			</div>
		{/snippet}
	{#if embedded}
		<section class="gal-sec home-tw">
			<div class="home-tw-head">
				<h2 class="home-tw-title">Most borrowed last&nbsp;month{#if monthLabel}{" "}<span class="home-tw-month">({monthShort})</span>{/if}</h2>
				<button class="home-tw-more" onclick={onSeeAll}>See all Most&nbsp;Borrowed →</button>
			</div>
			{@render galRow(overallBooks)}
		</section>
	{:else}
			<header class="rank-masthead">
				<h2 class="rank-title">{genre === "All genres" ? "Seattle's Most-Borrowed Books" : `Most-Borrowed ${genreLabel(genre)} Books`}</h2>
				<p class="rank-sub">Ranked by checkouts at the Seattle Public Library.</p>
			</header>
		<div class="ta-controls">
			<label class="ta-field">
				<span>Show</span>
				<select value={rankKind} onchange={(e) => setRankKind(e.currentTarget.value)}>
					<option value="works">Works</option>
					<option value="authors">Authors</option>
				</select>
			</label>
			<label class="ta-field">
				<span>Genre</span>
				<select bind:value={genre} onchange={() => (overallList = false)}>
					{#each genreList as g}
						<option value={g}>{genreLabel(g)}</option>
					{/each}
					{#if extra.length}
						<optgroup label="More genres">
							{#each extra as g}
								<option value={g}>{g}</option>
							{/each}
						</optgroup>
					{/if}
				</select>
			</label>
			<label class="ta-field">
				<span>Year</span>
				<select bind:value={year}>
					{#if latestMonth}<option value="month">Last month ({monthShort})</option>{/if}
					<option value="all">All time</option>
					{#each [...data.years].reverse() as y}
						<option value={String(y)}>{y}</option>
					{/each}
				</select>
			</label>
			<div class="share-wrap">
				<button class="chart-action" onclick={() => (shareOpen = !shareOpen)} title="Share this view" aria-haspopup="true" aria-expanded={shareOpen}>
					<ShareIcon size={14} strokeWidth={2.2} aria-hidden="true" /> <span class="ca-label">Share</span>
				</button>
				{#if shareOpen}
					<button class="share-backdrop" aria-label="Close share menu" onclick={() => (shareOpen = false)}></button>
					<div class="share-menu" role="menu">
